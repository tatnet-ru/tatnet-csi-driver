// Package driver реализует CSI-драйвер блочных томов TatNet.
//
// Три сервиса CSI живут в одном бинаре и включаются флагом `-mode`:
//
//   - controller — говорит с /v1 платформы: создаёт, удаляет, прикрепляет,
//     открепляет и растит тома. Здесь и только здесь есть ключ API.
//   - node — работает с устройством, которое уже принесли: находит его по
//     серийнику, форматирует, монтирует. Кредов платформы у него НЕТ.
//   - identity — общий для обоих.
//
// Разделение не косметическое: node-плагин крутится DaemonSet'ом на КАЖДОЙ
// ноде кластера, включая те, куда попадает клиентская нагрузка. Ключ проекта
// там означал бы, что он лежит на каждой машине клиента.
package driver

// DriverName — имя, под которым драйвер регистрируется в kubelet и которое
// стоит в StorageClass.provisioner. Стабильно: смена имени осиротит все
// существующие PV.
const DriverName = "block.csi.tatnet.ru"

// Version подставляется линкером при сборке.
var Version = "dev"

// Config — общие параметры обоих режимов.
type Config struct {
	Endpoint string // unix-сокет CSI

	// --- controller ---
	APIBase   string
	ProjectID string
	APIKey    string
	RegionID  string // регион, в котором создаются тома этого кластера
	// K8sClusterID — кластер, которому принадлежат создаваемые тома
	// (`managed_by='csi'`). Не косметика: на этой паре держится и снос кластера
	// (оркестратор помечает ИМЕННО такие тома), и авторизация — ключ драйвера
	// имеет скоуп `k8s_cluster:<id>`, и без кластера в теле запроса api вешает
	// ссылку создаваемого тома на проект, которого скоуп не покрывает.
	K8sClusterID string

	// --- node ---
	// NodeID — идентификатор ВМ TatNet, к которой прикрепляются тома. Читается
	// из файла, который оркестратор кладёт в машинный конфиг ноды: спрашивать
	// его у платформы было бы нельзя (кредов на ноде нет), а выводить из имени
	// ноды Kubernetes — значит связать две системы имён, которые меняются
	// независимо.
	NodeID string
}
